/**
 * Translate a key for the selected interface language. English is used as a
 * fallback so a missing translation never turns into an empty UI.
 *
 * @param {'en'|'bn'} language
 * @param {string} key
 * @param {Record<string, unknown>} [params]
 * @returns {string}
 */
export function t(language, key, params = {}) {
  const dictionary = STRINGS[language] ?? STRINGS.en;
  const template = dictionary[key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}

